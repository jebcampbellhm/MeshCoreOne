"""Reproduce the public OTA test vector using Python SHA-256 and OpenSSL Ed25519.

The private key is a fixed PUBLIC TEST KEY, never a firmware signing credential.
Run: python ci/generate_mota_fixture.py --openssl /path/to/openssl
"""
import argparse
import base64
import hashlib
from pathlib import Path
import struct
import subprocess
import tempfile
import textwrap


def digest(data):
    return hashlib.sha256(data).digest()


def root(leaves):
    peaks = []
    for leaf in leaves:
        level = 0
        while level < len(peaks) and peaks[level] is not None:
            leaf = digest(peaks[level] + leaf)[:4]
            peaks[level] = None
            level += 1
        if level == len(peaks):
            peaks.append(leaf)
        else:
            peaks[level] = leaf
    result = None
    for peak in peaks:
        if peak is not None:
            result = peak if result is None else digest(peak + result)[:4]
    return result


def generate(openssl):
    hardware = b"Heltec_tower_v2".ljust(32, b"\0")
    version, target = 0x01120100, 0x0A9DBBF0
    body = bytes((i * 17 + 3) % 256 for i in range(41))
    payload = body + b"EndF" + struct.pack("<I", len(body)) + digest(body)[:8]
    payload += struct.pack("<II", version, target) + hardware
    block_size = 32  # four blocks, last short; separate seven-leaf root test below
    leaves = [digest(payload[i:i + block_size])[:4] for i in range(0, len(payload), block_size)]
    manifest = bytearray([2, 3, 0x12])
    manifest += struct.pack("<IIII", target, version, len(payload), len(payload))
    manifest += bytes([5]) + root(leaves) + digest(payload) + bytes([0]) + hardware + bytes(8)
    with tempfile.TemporaryDirectory() as directory:
        path = Path(directory)
        key = path / "public-test-key.der"
        key.write_bytes(bytes.fromhex("302e020100300506032b657004220420") + bytes(range(32)))
        public = subprocess.check_output([
            openssl, "pkey", "-inform", "DER", "-in", str(key), "-pubout", "-outform", "DER"
        ])[-32:]
        manifest += public
        (path / "manifest").write_bytes(manifest)
        signature = subprocess.check_output([
            openssl, "pkeyutl", "-sign", "-rawin", "-keyform", "DER", "-inkey", str(key),
            "-in", str(path / "manifest")
        ])
    manifest += signature + bytes([255] * 4)
    size = 8 + 197 + len(leaves) * 4 + len(payload) + 5
    container = b"mOTA" + struct.pack("<I", size) + manifest + b"".join(leaves) + payload + b"vk496"
    descriptor = root(leaves) + struct.pack("<II", target, version) + bytes([0, 3])
    descriptor += struct.pack("<IIIII", size, 205, len(leaves), 205 + len(leaves) * 4, len(payload))
    descriptor += bytes([5, 0, 0, 0])
    seven = [digest(bytes([i]))[:4] for i in range(7)]
    encoded = base64.b64encode(container).decode()
    literal = " +\n    ".join('"' + part + '"' for part in textwrap.wrap(encoded, 100))
    source = """// Generated by ci/generate_mota_fixture.py; public test key only.
import Foundation

enum MotaReferenceFixture {
  static let container = Data(base64Encoded:
    %s
  )!
  static let descriptor = Data(base64Encoded: "%s")!
  static let sevenLeafRoot = Data(base64Encoded: "%s")!
}
""" % (literal, base64.b64encode(descriptor).decode(), base64.b64encode(root(seven)).decode())
    destination = Path(__file__).resolve().parents[1] / "MeshCore/Tests/MeshCoreTests/Fixtures/MotaReferenceFixture.swift"
    destination.write_text(source, encoding="utf-8", newline="\n")
    print(f"Generated {len(container)}-byte signed fixture; SHA256 {digest(container).hex()}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--openssl", default="openssl")
    generate(parser.parse_args().openssl)
